#!/usr/bin/env python3
"""Regenerate Lake build batches for the Solution's local import closure.

Lake's library `needs` dependencies are awaited before processing a module.
Two-module batches bound concurrent project compilations without introducing
Lean imports, changing proof terms, or replacing the trusted proof checker.
Run this after changing the Solution's imports or their transitive imports.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "# BEGIN GENERATED PALOMAR BUILD BATCHES"
END = "# END GENERATED PALOMAR BUILD BATCHES"
IMPORT = re.compile(r"^(?:public\s+)?import\s+(?:all\s+)?([A-Za-z0-9_.]+)\s*(?:--.*)?$", re.M)


def local_path(module):
    path = ROOT / (module.replace(".", "/") + ".lean")
    return path if path.is_file() else None


def imports(module):
    path = local_path(module)
    if path is None:
        return []
    source = path.read_text()
    result = IMPORT.findall(source)
    # Refuse to silently omit a newly introduced header syntax.
    header_lines = re.findall(r"^(?:public\s+)?import\s+.+$", source, re.M)
    if len(header_lines) != len(result):
        raise ValueError("Unsupported import header in " + str(path))
    return [name for name in result if local_path(name) is not None]


ordered = []
done = set()
active = set()


def visit(module):
    if module in done:
        return
    if module in active:
        raise ValueError("Import cycle at " + module)
    active.add(module)
    for dep in sorted(set(imports(module))):
        visit(dep)
    active.remove(module)
    done.add(module)
    if module != "Solution":
        ordered.append(module)


visit("Solution")
assert all(name.startswith("SptClassification.") for name in ordered)
assert ordered
positions = {name: i for i, name in enumerate(ordered)}
for name in ordered:
    assert all(positions[dep] < positions[name] for dep in imports(name))

lines = [BEGIN,
         "# Generated by scripts/update_palomar_build.py; do not reorder manually.",
         "# Each batch waits for the previous batch before any module processing."]
previous = None
for offset in range(0, len(ordered), 2):
    name = "PalomarBatch%03d" % (offset // 2 + 1)
    roots = ordered[offset:offset + 2]
    lines += ["", "[[lean_lib]]", 'name = "' + name + '"',
              "roots = [" + ", ".join('"' + x + '"' for x in roots) + "]"]
    if previous:
        lines.append('needs = ["' + previous + '"]')
    lines.append("leanOptions = { autoImplicit = false, weak.linter.mathlibStandardSet = true }")
    previous = name
lines += ["", "[[lean_lib]]", 'name = "Palomar"',
          'roots = ["Challenge", "Solution"]',
          'needs = ["' + previous + '"]',
          "leanOptions = { autoImplicit = false }", END]

config = ROOT / "lakefile.toml"
text = config.read_text()
if BEGIN in text:
    prefix, rest = text.split(BEGIN, 1)
    _, suffix = rest.split(END, 1)
else:
    old = '\n[[lean_lib]]\nname = "Palomar"\nroots = ["Challenge", "Solution"]\nleanOptions = { autoImplicit = false }\n'
    if old not in text:
        raise ValueError("Cannot locate the existing Palomar library")
    prefix = text.replace(old, "") + "\n"
    suffix = "\n"
config.write_text(prefix + "\n".join(lines) + suffix)
print("Configured %d project modules in %d sequential batches (at most two modules each)."
      % (len(ordered), (len(ordered) + 1) // 2))
